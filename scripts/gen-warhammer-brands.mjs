// Writes warhammer-common/brands.css: the white car brand logos of the R- overlays
// as `.wh-brand.<brand>` classes, so the Warhammer overlays draw logos without
// importing the whole R- stylesheet. Run it again when the R- logos change.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const repo = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const overlays = path.join(repo, 'racelink/src/renderer/widgets/overlays');
const source = fs.readFileSync(path.join(overlays, 'r-common/driver.css'), 'utf8');

const rule = /\.carBrandDefinitions\.([a-z0-9_]+)\.white::after\s*\{([^}]*)\}/g;
const lines = [
  '/* GENERATED by scripts/gen-warhammer-brands.mjs from r-common/driver.css. DO NOT EDIT. */',
  '.wh-brand {',
  '  display: inline-block;',
  '  background: center / contain no-repeat;',
  '  opacity: 0.9;',
  '}',
];
let count = 0;
for (const match of source.matchAll(rule)) {
  const [, brand, body] = match;
  const url = /url\(\.\/assets\/([0-9a-f]+\.png)\)/.exec(body ?? '');
  if (!url) continue;
  lines.push(`.wh-brand.${brand} { background-image: url('../r-common/assets/${url[1]}'); }`);
  count += 1;
}
// Unknown makes show the iRacing mark, as the R- overlays do.
const mark = lines.find((line) => line.startsWith('.wh-brand.iracing'));
if (mark !== undefined) lines.push(mark.replace('.iracing', '.n_a'));
fs.writeFileSync(path.join(overlays, 'warhammer-common/brands.css'), `${lines.join('\n')}\n`);
console.log(`${String(count)} brand logos`);
